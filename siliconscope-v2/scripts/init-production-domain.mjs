import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const root = process.cwd();
const args = process.argv.slice(2);
const force = args.includes("--force");
const domainArg = args.find((arg) => !arg.startsWith("--"));

function usage() {
  console.log("Usage: npm run deploy:init -- your-domain.com [--force]");
  console.log("Creates .env.production for a one-VPS independent-domain deployment.");
}

function normalizeDomain(input) {
  if (!input) return "";
  return input
    .trim()
    .replace(/^https?:\/\//i, "")
    .replace(/^www\./i, "")
    .replace(/\/+$/, "")
    .toLowerCase();
}

function secret(bytes = 32) {
  return crypto.randomBytes(bytes).toString("base64url");
}

const baseDomain = normalizeDomain(domainArg);
if (!baseDomain || !baseDomain.includes(".")) {
  usage();
  process.exit(1);
}

const envPath = path.resolve(root, ".env.production");
if (fs.existsSync(envPath) && !force) {
  console.error(`Refusing to overwrite ${envPath}. Re-run with --force if you really want to replace it.`);
  process.exit(1);
}

